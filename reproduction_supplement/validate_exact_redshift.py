"""Independent checks for the four same-DES redshift analyses."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

from exact_redshift_checks import CASES, ExactRedshiftModel, OUT, frame_term
from supplement_diagnostics import predict_joint

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def sha(arrays):
    h = hashlib.sha256()
    for arr in arrays:
        h.update(np.asarray(arr).tobytes())
    return h.hexdigest()


def main():
    report = {"cases": [], "checks": []}
    # Preserve the actual factor used by the frozen chains before constructors
    # regenerate factors. GP BLAS reductions can differ at ~1e-13 mag across
    # thread settings. Hash the frozen input exactly; compare recomputation
    # numerically instead of pretending its newly generated bytes must agree.
    frozen = {case: dict(np.load(OUT / f"{case}_distance_factor.npz")) for case in CASES}
    base = ExactRedshiftModel("signed_envelope")
    original = json.loads((ROOT / "reproduction_physical" / "nonlinear_base_summary.json").read_text())
    baseline_ppc = json.loads((HERE / "diagnostics" / "analytic_source_trend_checks.json").read_text())
    base_source_probability = baseline_ppc["primary_raw_source_redshift"]["analytic_posterior_predictive_probability"]
    for case in CASES:
        model = ExactRedshiftModel(case)
        folder = OUT / case
        summary = json.loads((folder / "joint_summary.json").read_text())
        d = json.loads((folder / "diagnostics.json").read_text())
        factor = frozen[case]
        chain = np.load(folder / "joint_chains.npy", mmap_mode="r")
        mu = np.load(folder / "joint_mu.npy", mmap_mode="r")
        assert model.df["Lens name"].tolist() == base.df["Lens name"].tolist()
        assert np.array_equal(factor["selected_indices"], np.r_[model.df.sn_lens_idx, model.df.sn_source_idx])
        assert len(np.unique(factor["selected_indices"])) == 176
        assert model.bounds[0][0] == -0.09405370006986057 and model.bounds[2] == (-.5, .5)
        assert chain.shape == (4, 100000, 5) and mu.shape == (4, 666, 176)
        assert np.array_equal(np.asarray(summary["mu_saved_indices"]), np.arange(33400, 100000, 100))
        assert summary["convergence_screen"] and summary["diagnostics"]["max_rhat"] < 1.01
        assert summary["diagnostics"]["min_ess"] > 1000
        assert np.isfinite(chain).all() and np.isfinite(mu).all()
        q = np.percentile(chain[:, summary["burn"]:, :], [15.865, 50, 84.135], axis=(0, 1))
        assert np.allclose(q, summary["quantiles"], atol=2e-6, rtol=0)
        assert np.allclose(q[:, 0], d["Omega_quantiles"], atol=1e-12)
        assert np.allclose(q[:, 2], d["gamma_z_quantiles"], atol=1e-12)
        assert q[0, 0] < 0 < q[2, 0]
        covariance = factor["covariance"]
        assert np.allclose(covariance, covariance.T, atol=1e-10)
        np.linalg.cholesky(covariance)
        regenerated_mean = np.r_[model.ml, model.ms]
        regenerated_covariance = np.block([[model.cl, model.cls], [model.cls.T, model.cs]])
        assert np.allclose(factor["mean"], regenerated_mean, atol=2e-10, rtol=0)
        assert np.allclose(covariance, regenerated_covariance, atol=2e-12, rtol=0)
        original_hash = sha([factor["mean"], covariance, model.zl, model.zs,
                             model.te, model.ta, model.delta, model.obs, model.err, np.asarray(model.bounds, float)])
        assert original_hash == summary["input_array_sha256"]
        assert np.isfinite(d["source_redshift_PPC_analytic"])
        assert d["joint_states"] == 2664
        # The conditional velocity likelihood must remain numerically valid
        # for saved, exactly aligned parameter/latent-distance states.
        indices = np.asarray(summary["mu_saved_indices"])
        theta = np.asarray(chain[:, indices, :]).reshape(-1, 5)
        latent = np.asarray(mu).reshape(-1, 176)
        selected = np.linspace(0, len(theta) - 1, 24, dtype=int)
        prediction, variance = predict_joint(model, theta[selected], latent[selected])
        assert prediction.shape == variance.shape == (len(selected), 88)
        assert np.isfinite(prediction).all() and np.all(variance > 0)
        report["cases"].append({"name": case,
                                "frozen_fit_input_hash_verified": True,
                                "recomputed_mean_max_abs_difference_mag": float(np.max(abs(factor["mean"]-regenerated_mean))),
                                "recomputed_covariance_max_abs_difference_mag2": float(np.max(abs(covariance-regenerated_covariance))),
                                "Omega_quantiles": q[:, 0].tolist(),
                                "gamma_z_quantiles": q[:, 2].tolist(),
                                "source_redshift_PPC": d["source_redshift_PPC_analytic"],
                                "partial_source_redshift_PPC": d["partial_source_redshift_PPC_analytic"],
                                "overall_PPC": d["overall_squared_residual_PPC_analytic"],
                                "max_Rhat": summary["diagnostics"]["max_rhat"],
                                "min_ESS": summary["diagnostics"]["min_ess"],
                                "median_distance_sigma_mag": float(np.median(np.sqrt(np.diag(covariance))))})
    signed = np.load(OUT / "signed_envelope_distance_factor.npz")
    signed_no = np.load(OUT / "signed_no_envelope_distance_factor.npz")
    assert np.allclose(signed["mean"], signed_no["mean"], atol=1e-12)
    assert np.allclose(signed["covariance"] - signed_no["covariance"],
                       np.diag(signed["fiducial_signed_shift"] ** 2), atol=1e-12)
    assert np.allclose(signed["frame_corrected"],
                       signed["observed"] - frame_term(signed["train_zHEL"], signed["train_zHD"]), atol=1e-12)
    assert np.allclose(signed["mean"], signed["frame_corrected"] + signed["fiducial_signed_shift"], atol=1e-12)
    assert np.allclose(original["quantiles"][1][0], .107398126, atol=.001)
    report["baseline"] = {"Omega_quantiles": np.asarray(original["quantiles"])[:, 0].tolist(),
                          "gamma_z_quantiles": np.asarray(original["quantiles"])[:, 2].tolist(),
                          "source_redshift_PPC": base_source_probability}
    report["checks"] = ["unchanged lens and DES-row identities", "same curvature/evolution priors",
                         "full covariance and positive definite distance factors", "signed transfer and frame correction",
                         "saved chain quantiles and aligned latent iterations", "input-array hashes",
                         "finite conditional lens predictions", "rank/folded convergence screens"]
    (OUT / "validation.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps({"runs": len(report["cases"]), "largest_rhat": max(x["max_Rhat"] for x in report["cases"]),
                      "smallest_ESS": min(x["min_ESS"] for x in report["cases"]),
                      "source_PPC_range": [min(x["source_redshift_PPC"] for x in report["cases"]),
                                           max(x["source_redshift_PPC"] for x in report["cases"])]}, indent=2))


if __name__ == "__main__":
    main()
